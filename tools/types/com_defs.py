# Eine abgeleitete Schnittstelle darf eine geerbte Methode gleichen Namens neu deklarieren (anderer
# Parametersatz, gleicher Slot), z. B. IDirectDraw2::SetDisplayMode mit 5 Parametern.


def methods(name):
    """Alle Methoden einer Schnittstelle in Slot-Reihenfolge (inklusive geerbter): [(slot, signatur, deklariert_in)]."""
    chain = []
    n = name
    while n:
        chain.append(n)
        n = INTERFACES[n][0]
    out = []
    for iface in reversed(chain):
        for sig in INTERFACES[iface][1]:
            nm = method_name(sig)
            k = next((k for k, (_, s, _) in enumerate(out) if method_name(s) == nm), None)
            if k is None:
                out.append((len(out), sig, iface))
            else:
                out[k] = (k, sig, iface)
    return out


def method_name(sig):
    return sig.split('(')[0].split()[-1].lstrip('*')
